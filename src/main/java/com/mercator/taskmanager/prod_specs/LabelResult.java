package com.mercator.taskmanager.prod_specs;

/** Итог разметки одной карточки (шаг 1 рекомендаций по закупкам). */
public enum LabelResult {
    /** Признаки получены от модели и записаны. */
    LABELED,
    /** Данные карточки и версия промпта не менялись, запрос не нужен. */
    UP_TO_DATE,
    /** У карточки нет адреса фото. */
    NO_IMAGE,
    /** У карточки нет полного набора (content_txt). */
    NO_CONTENT,
    /** Карточки с таким id нет. */
    NOT_FOUND,
    /** Модель не ответила или ответ непригоден. */
    FAILED
}